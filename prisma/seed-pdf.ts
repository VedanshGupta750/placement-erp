// Builds a tiny but genuinely valid PDF, so seeded demo resumes are real
// downloadable files rather than Resume rows with no File behind them.
//
// Written by hand rather than with @react-pdf/renderer (which this app does
// depend on) because the seed is a plain Node script: pulling a React
// renderer in just to draw five lines of text would make seeding slower and
// far more fragile than the ~1 KB of bytes it produces.
//
// A PDF's xref table stores the byte offset of every object, so the offsets
// are measured as the body is built — that is what makes the file valid in
// Acrobat and Chrome's viewer, not just "openable" in tolerant readers.

function escapePdfText(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
}

/** A one-page PDF containing the given lines, as a base64 data URI. */
export function buildPlaceholderPdf(title: string, lines: string[]): string {
  const drawn = [
    `BT /F1 18 Tf 56 770 Td (${escapePdfText(title)}) Tj ET`,
    ...lines.map((line, i) => `BT /F1 11 Tf 56 ${738 - i * 18} Td (${escapePdfText(line)}) Tj ET`),
  ].join("\n");

  const objects: Record<number, string> = {
    1: "<< /Type /Catalog /Pages 2 0 R >>",
    2: "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    3: "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
    4: `<< /Length ${Buffer.byteLength(drawn, "latin1")} >>\nstream\n${drawn}\nendstream`,
    5: "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
  };

  let pdf = "%PDF-1.4\n";
  const offsets: number[] = [];
  for (let i = 1; i <= 5; i += 1) {
    offsets[i] = Buffer.byteLength(pdf, "latin1");
    pdf += `${i} 0 obj\n${objects[i]}\nendobj\n`;
  }

  const xrefOffset = Buffer.byteLength(pdf, "latin1");
  pdf += "xref\n0 6\n0000000000 65535 f \n";
  for (let i = 1; i <= 5; i += 1) {
    pdf += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;

  const base64 = Buffer.from(pdf, "latin1").toString("base64");
  return `data:application/pdf;base64,${base64}`;
}

/** The demo resume used for every seeded student. */
export function buildDemoResume(studentName: string, course: string, enrollmentNumber: string): string {
  return buildPlaceholderPdf(studentName, [
    `Enrollment number: ${enrollmentNumber}`,
    `Programme: ${course}`,
    "",
    "This is sample data generated by prisma/seed.ts.",
    "It exists so the resume download path can be exercised",
    "end to end in a demo environment. It is not a real resume.",
  ]);
}
